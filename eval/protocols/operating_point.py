"""Experiment `operating_point`: turn the open-set results into thresholds, and write
docs/OPERATING_POINT.md.

Thresholds are chosen on the TUNE split (FPIR target on its non-mated searches) and then
applied, unchanged, to the TEST split to measure FNIR and the real FPIR.
Alert-load model: false alerts/day = uploads/day x faces/upload x FPIR(test).
"""
import os

import numpy as np
import pandas as pd

from eval import metrics as M
from eval.common import ROOT, git_commit, load_result, metadata, save_result
from eval.datasets import lfw
from eval.protocols import openset

TARGETS = [0.001, 0.005, 0.01, 0.02, 0.05]


def fixed_threshold_stats(recs, t, n_boot, seed):
    units = openset.to_units(recs)
    a = M.bootstrap_ci(lambda us: M.fnir_fpir_at_threshold(*openset.unit_arrays(us), t)[0], units, n=n_boot, seed=seed)
    b = M.bootstrap_ci(lambda us: M.fnir_fpir_at_threshold(*openset.unit_arrays(us), t)[1], units, n=n_boot, seed=seed)
    return {"fnir": a[0], "fnir_ci": [a[1], a[2]], "fpir": b[0], "fpir_ci": [b[1], b[2]]}


def run(cfg):
    gallery = cfg.get("gallery_size", 1000)
    uploads, faces = float(cfg.get("uploads_per_day", 200)), float(cfg.get("faces_per_upload", 4))
    n_boot, seed = int(cfg.get("n_boot", 1000)), int(cfg["seed"])
    match_fpir, high_fpir = float(cfg.get("match_fpir", 0.01)), float(cfg.get("high_fpir", 0.001))
    tune = pd.read_csv(openset.records_path("tune", gallery))
    test = pd.read_csv(openset.records_path("test", gallery))
    tune_non = tune[~tune["mated"]]["top_score"].to_numpy(float)

    rows = []
    for target in sorted(set(TARGETS) | {match_fpir, high_fpir}):
        t = M.threshold_at_rate(tune_non, target)
        st = fixed_threshold_stats(test, t, n_boot, seed)
        rows.append({"fpir_target": target, "threshold_tune": t, **{f"test_{k}": v for k, v in st.items()},
                     "false_alerts_per_day": uploads * faces * st["fpir"],
                     "false_alerts_per_day_ci": [uploads * faces * st["fpir_ci"][0], uploads * faces * st["fpir_ci"][1]]})
    by_target = {r["fpir_target"]: r for r in rows}
    import config
    previous = {"MATCH_THRESHOLD": config.MATCH_THRESHOLD, "HIGH_CONF_THRESHOLD": config.HIGH_CONF_THRESHOLD}
    # Stability rule: keep the deployed value when it lies inside the bootstrap CI of the re-measured
    # tune threshold (re-splitting identities alone moves thresholds by about that much).
    tune_ci = load_result("openset_lfw")["splits"]["tune"]["by_gallery_size"][str(gallery)]["fnir_at_fpir"]
    measured = {"MATCH_THRESHOLD": round(by_target[match_fpir]["threshold_tune"], 3),
                "HIGH_CONF_THRESHOLD": round(by_target[high_fpir]["threshold_tune"], 3)}
    cis = {"MATCH_THRESHOLD": tune_ci[str(match_fpir)]["threshold_ci"], "HIGH_CONF_THRESHOLD": tune_ci[str(high_fpir)]["threshold_ci"]}
    rec = {"match_fpir": match_fpir, "high_fpir": high_fpir, "measured": measured, "measured_ci": cis, "kept": {}}
    for k in measured:
        lo, hi = cis[k]
        keep = lo is not None and lo <= previous[k] <= hi
        rec[k] = previous[k] if keep else measured[k]
        rec["kept"][k] = bool(keep)
    prev_stats = {k: fixed_threshold_stats(test, v, n_boot, seed) for k, v in previous.items()}
    result = {"meta": metadata(cfg, lfw.DATASET_VERSION), "gallery_size": gallery,
              "uploads_per_day": uploads, "faces_per_upload": faces, "table": rows,
              "recommended": rec, "previous": previous, "previous_test_stats": prev_stats,
              "n_test_mated": int(test["mated"].sum()), "n_test_nonmated": int((~test["mated"]).sum()),
              "n_tune_nonmated": int(tune_non.size),
              "top_tune_nonmated_scores": sorted(tune_non.tolist(), reverse=True)[:5]}
    save_result("operating_point", result)
    if not os.environ.get("LOCATENET_EVAL_RESULTS"):  # regression runs must not rewrite the docs
        write_doc(result)
    print(f"Recommended MATCH_THRESHOLD={rec['MATCH_THRESHOLD']} (FPIR {match_fpir:.1%}), "
          f"HIGH_CONF_THRESHOLD={rec['HIGH_CONF_THRESHOLD']} (FPIR {high_fpir:.1%})")


def _pct(x):
    return "n/a" if x is None or not np.isfinite(x) else f"{100 * x:.2f}%"


def write_doc(r):
    rec = r["recommended"]
    by = {row["fpir_target"]: row for row in r["table"]}
    m = by[rec["match_fpir"]]
    if rec.get("kept", {}).get("MATCH_THRESHOLD"):
        m = {**m, **{f"test_{k}": v for k, v in r["previous_test_stats"]["MATCH_THRESHOLD"].items()},
             "false_alerts_per_day": r["uploads_per_day"] * r["faces_per_upload"] * r["previous_test_stats"]["MATCH_THRESHOLD"]["fpir"]}
    lines = [
        "# Operating point",
        "",
        "Generated by `python -m eval run eval/config/operating_point.yaml` from "
        "`eval/results/operating_point.json` (commit `" + r["meta"]["git_commit"][:12] + "`). Do not edit by hand.",
        "",
        "## How the thresholds were chosen",
        "",
        "- Data: LFW open-set protocol (`eval/protocols/openset.py`), gallery of "
        f"{r['gallery_size']} enrolled identities, one reference photo each.",
        "- Each threshold is the score at which the target share of **non-mated** searches on the "
        "**tune** split raise an alert (FPIR). It is then applied unchanged to the **test** split "
        "(different people) to measure the miss rate (FNIR) and the real FPIR.",
        f"- Alert-load model: {r['uploads_per_day']:.0f} sighting uploads/day x {r['faces_per_upload']:.0f} faces/upload "
        "x FPIR = expected false alerts/day. The app raises at most one alert per upload, so this is an upper bound. "
        "Both numbers are parameters in `eval/config/operating_point.yaml`.",
        "",
        "## Options",
        "",
        "| FPIR target (tune) | Threshold | FNIR on test [95% CI] | FPIR on test [95% CI] | False alerts/day |",
        "|---|---|---|---|---|",
    ]
    for row in r["table"]:
        lines.append(
            f"| {_pct(row['fpir_target'])} | {row['threshold_tune']:.3f} | {_pct(row['test_fnir'])} "
            f"[{_pct(row['test_fnir_ci'][0])}, {_pct(row['test_fnir_ci'][1])}] | {_pct(row['test_fpir'])} "
            f"[{_pct(row['test_fpir_ci'][0])}, {_pct(row['test_fpir_ci'][1])}] | {row['false_alerts_per_day']:.1f} |")
    prev = r["previous_test_stats"]["MATCH_THRESHOLD"]
    lines += [
        "",
        "## Decision",
        "",
        f"- **MATCH_THRESHOLD = {rec['MATCH_THRESHOLD']}** (FPIR {_pct(rec['match_fpir'])} on tune). On the test split it misses "
        f"{_pct(m['test_fnir'])} of mated searches and alerts on {_pct(m['test_fpir'])} of non-mated ones, "
        f"about {m['false_alerts_per_day']:.1f} false alerts/day at the assumed load.",
        f"- **HIGH_CONF_THRESHOLD = {rec['HIGH_CONF_THRESHOLD']}** (FPIR {_pct(rec['high_fpir'])} on tune), used only for the "
        "\"High Similarity\" label.",
        *[f"- Stability rule: the re-measured {k} is {rec['measured'][k]} (tune 95% CI {rec['measured_ci'][k][0]:.3f}-"
          f"{rec['measured_ci'][k][1]:.3f}); the deployed value {r['previous'][k]} lies inside that CI, so it is kept."
          for k in ("MATCH_THRESHOLD", "HIGH_CONF_THRESHOLD") if rec.get("kept", {}).get(k)],
        "- Why FPIR 1%: every alert is reviewed by an officer, so a false alert costs a few minutes of review, while a "
        "missed match can cost a missing person. "
        f"On LFW the 0.5% point is almost as good (FNIR {_pct(by[0.005]['test_fnir'])} vs {_pct(m['test_fnir'])}, "
        f"overlapping CIs) with fewer false alerts ({by[0.005]['false_alerts_per_day']:.1f} vs "
        f"{m['false_alerts_per_day']:.1f}/day), but real sightings have lower genuine scores than LFW, and the lower "
        "1% threshold keeps more of them above the line. "
        f"The 0.1% point would push FNIR to {_pct(by[0.001]['test_fnir'])}; the 5% point adds "
        f"{by[0.05]['false_alerts_per_day'] - m['false_alerts_per_day']:.0f} false alerts/day for "
        f"{_pct(m['test_fnir'] - by[0.05]['test_fnir'])} less FNIR.",
        f"- The 0.1% threshold ({rec['HIGH_CONF_THRESHOLD']}) is set by the two highest non-mated scores among "
        f"{r['n_tune_nonmated']} tune searches (likely look-alikes or LFW label errors), so it is fragile. It only "
        "controls the \"High Similarity\" label, not whether an alert is raised.",
        f"- The deployed MATCH_THRESHOLD before this run ({r['previous']['MATCH_THRESHOLD']}) gives FNIR {_pct(prev['fnir'])} and "
        f"FPIR {_pct(prev['fpir'])} on the same test split.",
        "",
        "## Caveats",
        "",
        "- LFW photos are mostly frontal, well lit celebrity photos. Real sightings (phone photos, CCTV, crowds) "
        "produce lower genuine scores, so the real FNIR will be higher than above; see the robustness results in "
        "`docs/EVALUATION.md`.",
        "- FPIR depends on gallery size: more enrolled cases means more chances for a false rank-1 hit. Re-run this "
        "experiment when the number of active cases changes by an order of magnitude.",
        f"- The test split has {r['n_test_nonmated']} non-mated searches, so FPIR = 0.1% rests on only a few errors and "
        "its CI is wide.",
        "",
    ]
    path = os.path.join(ROOT, "docs", "OPERATING_POINT.md")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"Wrote {os.path.relpath(path, ROOT)} (commit {git_commit()[:12]})")
